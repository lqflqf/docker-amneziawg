// Package render turns the state into conf text: the server wg0.conf, the
// peer exports and the dnsmasq conf.
package render

import (
	"fmt"
	"strings"

	"github.com/lqflqf/docker-amneziawg/internal/awg"
	"github.com/lqflqf/docker-amneziawg/internal/conf"
	"github.com/lqflqf/docker-amneziawg/internal/config"
	"github.com/lqflqf/docker-amneziawg/internal/keys"
	"github.com/lqflqf/docker-amneziawg/internal/store"
)

// ListenPort is the port the container listens on; SERVERPORT is only what
// peers dial.
const ListenPort = "51820"

// Interface is the wg0 name.
const Interface = "wg0"

// FirewallRules returns the PostUp and PostDown commands. The interface
// pattern was validated against a strict pattern, because awg-quick runs these
// lines through bash.
func FirewallRules(natIface string, ipv6Drop bool) (up, down []string) {
	if ipv6Drop {
		up = append(up, "ip6tables -I FORWARD -i %i -j DROP", "ip6tables -I FORWARD -o %i -j DROP")
	}
	up = append(up,
		"iptables -A FORWARD -i %i -j ACCEPT",
		"iptables -A FORWARD -o %i -j ACCEPT",
		"iptables -t nat -A POSTROUTING -o "+natIface+" -j MASQUERADE")
	down = append(down,
		"iptables -t nat -D POSTROUTING -o "+natIface+" -j MASQUERADE || true",
		"iptables -D FORWARD -o %i -j ACCEPT || true",
		"iptables -D FORWARD -i %i -j ACCEPT || true")
	if ipv6Drop {
		down = append(down, "ip6tables -D FORWARD -o %i -j DROP || true", "ip6tables -D FORWARD -i %i -j DROP || true")
	}
	return up, down
}

func addAWG(s *conf.Section, p awg.Params) {
	for _, l := range awg.Lines(p) {
		s.Add(l.Key, l.Value)
	}
}

func mtu(v string) string {
	if v == "none" {
		return ""
	}
	return v
}

// Server renders wg0.conf.
func Server(st *config.State) (*conf.File, error) {
	subnet := st.Subnet()
	iface := conf.Section{Name: "Interface"}
	iface.Add("Address", config.ServerAddress(subnet)+"/24")
	iface.Add("ListenPort", ListenPort)
	iface.Add("PrivateKey", st.Get(config.KeyServerPrivateKey))
	iface.Add("MTU", mtu(st.Get(config.KeyMTU)))
	up, down := FirewallRules(st.Get(config.KeyNATInterface), st.Bool(config.KeyIPv6ForwardDrop))
	for _, c := range up {
		iface.Add("PostUp", c)
	}
	for _, c := range down {
		iface.Add("PostDown", c)
	}
	addAWG(&iface, st.AWG)
	f := &conf.File{Sections: []conf.Section{iface}}
	keepalive := st.Get(config.KeyKeepaliveSeconds)
	for _, p := range st.Peers {
		if !p.Enabled {
			continue
		}
		s := conf.Section{Name: "Peer", Comments: []string{fmt.Sprintf("#%d %s", p.ID, p.Name)}}
		s.Add("PublicKey", p.PublicKey)
		s.Add("PresharedKey", p.PresharedKey)
		s.Add("AllowedIPs", config.PeerAddress(subnet, p.ID)+"/32")
		ka := "0"
		if p.Keepalive {
			ka = keepalive
		}
		s.Add("PersistentKeepalive", ka)
		f.Sections = append(f.Sections, s)
	}
	return f, f.Check()
}

// Peer renders the conf for one peer.
func Peer(st *config.State, p store.Peer) (*conf.File, error) {
	subnet := st.Subnet()
	serverPub, err := keys.Public(st.Get(config.KeyServerPrivateKey))
	if err != nil {
		return nil, fmt.Errorf("server key: %w", err)
	}
	iface := conf.Section{Name: "Interface"}
	iface.Add("Address", config.PeerAddress(subnet, p.ID)+"/32")
	iface.Add("PrivateKey", p.PrivateKey)
	iface.Add("MTU", mtu(st.Get(config.KeyPeerMTU)))
	iface.Add("DNS", config.ServerAddress(subnet))
	// I1-I5 must be in [Interface]: the Amnezia app ignores them under [Peer].
	addAWG(&iface, st.AWG)
	peer := conf.Section{Name: "Peer"}
	peer.Add("PublicKey", serverPub)
	peer.Add("PresharedKey", p.PresharedKey)
	peer.Add("Endpoint", st.Get(config.KeyEndpointHost)+":"+st.Get(config.KeyEndpointPort))
	peer.Add("AllowedIPs", st.Get(config.KeyAllowedIPs))
	f := &conf.File{Sections: []conf.Section{iface, peer}}
	return f, f.Check()
}

// Dnsmasq renders the whole dnsmasq conf. interface=wg0 with bind-dynamic
// answers only queries that arrive on wg0 (plus loopback, which only this
// container reaches). Never use listen-address: it answers on every interface.
func Dnsmasq(upstream string) string {
	var b strings.Builder
	b.WriteString(`# Generated by awgctl at each start. Do not edit.
user=dnsmasq
group=dnsmasq
no-resolv
bind-dynamic
interface=wg0
host-record=health.amneziawg,127.0.0.1
log-facility=-
domain-needed
bogus-priv
no-hosts
cache-size=1000
`)
	for _, s := range strings.Split(upstream, ",") {
		if s = strings.TrimSpace(s); s != "" {
			b.WriteString("server=" + s + "\n")
		}
	}
	return b.String()
}
